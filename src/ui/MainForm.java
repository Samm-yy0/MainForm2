        // TODO add your handling code here
        String studentID = txtStudentID.getText().trim();
        String fullName = txtFullName.getText().trim();
        String gradeLevel = (String) cmbGradeLevel.getSelectedItem();
        
        //        System.out.printf("%s,");
        
        boolean res = controller.handleAddStudent(studentID, fullName, gradeLevel);
        
        if (res) {
            JOptionPane.showMessageDialog(this, "New student added", "Student Registration", JOptionPane.INFORMATION_MESSAGE);
        }else{
            JOptionPane.showMessageDialog(this, "Error adding new student", "Student Registration", JOptionPane.ERROR_MESSAGE);
        }
